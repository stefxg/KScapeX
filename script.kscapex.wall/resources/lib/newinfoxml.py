"""KScapeX "New wall test": the movie info screen in its cinema look.

script-kscape-info-new.xml is the classic fiche (script-kscape-info.xml, hand-written)
transformed by transform() below - tools/gen_wall_xml.py writes it at build time, and the
classic file is never touched. The fiche keeps every control id, position and page, so
details.py drives both without knowing which one is open; only the dressing changes:

- the whole screen sits on the film's fanart (Window.Property(fanart), set by details.py),
  darkened by a veil, a left-hand gradient where the text is, and a vignette - with no
  fanart, the veil alone dims the wall behind;
- the panel becomes a slab of polished glass (the theme's background, translucent) instead of
  opaque blue: a sheen lying across it, a shadow pooling at its foot and a lit top edge; the
  left column a darker glass; the header strip a quiet band with a line in the theme colour
  under it;
- a selected row is lit from above (kscape-row.png) instead of a flat block of colour;
- the clear logo (Window.Property(clearlogo)) replaces the title when the library has one;
- it opens as a fade with a slight bloom (zoom 97 -> 100) instead of sliding up from the
  bottom, and closes as a fade - the wall behind already shows the same fanart, so the
  small panel reads as dissolving into the full fiche.

The wall opens this fiche only from New wall test (WallWindow.info_xml); everything else
keeps the classic one.
"""

NAME = 'script-kscape-info-new.xml'
REDUCED = '!String.IsEqual(Window(Home).Property(kscape.reduced),1)'

BACKDROP = '''			<control type="image">
				<description>The film's fanart behind everything (details.py sets the property)</description>
				<left>-120</left>
				<top>-60</top>
				<width>2160</width>
				<height>1200</height>
				<aspectratio>scale</aspectratio>
				<fadetime>300</fadetime>
				<texture background="true">$INFO[Window.Property(fanart)]</texture>
			</control>
			<control type="image">
				<description>Veil over the fanart (alone, it dims the wall when there is no fanart)</description>
				<left>-120</left>
				<top>-60</top>
				<width>2160</width>
				<height>1200</height>
				<texture colordiffuse="C8000000">kscape-white.png</texture>
			</control>
			<control type="image">
				<description>Darker towards the left, where the text sits</description>
				<left>-120</left>
				<top>-60</top>
				<width>1420</width>
				<height>1200</height>
				<texture colordiffuse="C8000000">kscape-hfade.png</texture>
			</control>
			<control type="image">
				<left>-120</left>
				<top>-60</top>
				<width>2160</width>
				<height>1200</height>
				<texture>kscape-vignette.png</texture>
			</control>
'''


def _swap(xml, old, new, count=1):
    found = xml.count(old)
    if found != count:
        raise ValueError(f'newinfoxml: expected {count} of {old[:60]!r}, found {found} - '
                         f'script-kscape-info.xml has changed; update newinfoxml.py')
    return xml.replace(old, new)


def transform(xml):
    """script-kscape-info-new.xml from the classic fiche's XML."""
    out = _swap(xml, '''<!-- Movie info screen (resources/lib/details.py). Hand-written.''',
                '''<!-- GENERATED by tools/gen_wall_xml.py from script-kscape-info.xml (resources/lib/newinfoxml.py):
     the cinema fiche of New wall test. Do not edit by hand; edit the classic file or the transform.
     Movie info screen (resources/lib/details.py).''')
    # It opens as a fade with a slight bloom, and closes as a fade (no slide from the bottom).
    out = _swap(out, f'''				<animation effect="slide" start="0,1032" end="0,0" time="420" tween="cubic" easing="out" condition="{REDUCED}">WindowOpen</animation>
				<animation effect="fade" start="0" end="100" time="160" condition="{REDUCED}">WindowOpen</animation>
				<animation effect="slide" start="0,0" end="0,1032" time="300" tween="cubic" easing="in" condition="{REDUCED}">WindowClose</animation>''',
                f'''				<animation effect="zoom" start="97" end="100" center="auto" time="300" tween="cubic" easing="out" condition="{REDUCED}">WindowOpen</animation>
				<animation effect="fade" start="0" end="100" time="260" condition="{REDUCED}">WindowOpen</animation>
				<animation effect="fade" start="100" end="0" time="200" condition="{REDUCED}">WindowClose</animation>''')
    # The fanart backdrop, behind the panel.
    out = _swap(out, '''			<include>KScapeDisplay</include>
''', '''			<include>KScapeDisplay</include>
''' + BACKDROP)
    # Smoked glass instead of opaque blue.
    out = _swap(out, '''				<control type="image">
					<width>1728</width>
					<height>984</height>
					<texture colordiffuse="kscape_blue">kscape-white.png</texture>
				</control>''', '''				<control type="image">
					<width>1728</width>
					<height>984</height>
					<texture colordiffuse="kscape_bg_veil">kscape-white.png</texture>
				</control>
				<control type="image">
					<description>Sheen lying across the glass</description>
					<width>1728</width>
					<height>984</height>
					<texture colordiffuse="A6FFFFFF">kscape-sheen.png</texture>
				</control>
				<control type="image">
					<description>Shadow pooling at the foot of the pane</description>
					<top>864</top>
					<width>1728</width>
					<height>120</height>
					<texture colordiffuse="59000000" flipy="true">kscape-fade.png</texture>
				</control>
				<control type="image">
					<width>1728</width>
					<height>984</height>
					<texture border="2" colordiffuse="28FFFFFF">kscape-glass-border.png</texture>
				</control>
				<control type="image">
					<description>Lit edge along the top</description>
					<width>1728</width>
					<height>1</height>
					<texture colordiffuse="6EFFFFFF">kscape-white.png</texture>
				</control>''')
    # A selected row is lit from above instead of a flat block of colour (every list's focused
    # row, and the menu's marker for the page that is open).
    out = _swap(out, '<texture colordiffuse="kscape_blue_light">kscape-white.png</texture>',
                '<texture colordiffuse="kscape_blue_light">kscape-row.png</texture>', count=7)
    out = _swap(out, '<texture colordiffuse="kscape_blue_mid">kscape-white.png</texture>',
                '<texture colordiffuse="kscape_blue_mid">kscape-row.png</texture>', count=1)
    out = _swap(out, '''					<description>Left column</description>
					<top>64</top>
					<width>480</width>
					<height>920</height>
					<texture colordiffuse="kscape_blue_dark">kscape-white.png</texture>''',
                '''					<description>Left column</description>
					<top>64</top>
					<width>480</width>
					<height>920</height>
					<texture colordiffuse="73000000">kscape-white.png</texture>''')
    # Header: a quiet band with a line in the theme colour, the clear logo in place of the title.
    out = _swap(out, '''				<control type="image">
					<description>Header strip</description>
					<width>1728</width>
					<height>64</height>
					<texture colordiffuse="kscape_blue_head">kscape-white.png</texture>
				</control>''', '''				<control type="image">
					<description>Header strip (quiet, on the glass)</description>
					<width>1728</width>
					<height>64</height>
					<texture colordiffuse="46000000">kscape-white.png</texture>
				</control>
				<control type="image">
					<top>61</top>
					<width>1728</width>
					<height>3</height>
					<texture colordiffuse="kscape_blue">kscape-white.png</texture>
				</control>''')
    out = _swap(out, '''				<control type="label">
					<left>30</left>
					<width>1660</width>
					<height>64</height>
					<aligny>center</aligny>
					<font>kscape_info_head</font>
					<textcolor>FFFFFFFF</textcolor>
					<label>$INFO[Window.Property(title)]</label>
				</control>''', '''				<control type="label">
					<left>30</left>
					<width>1660</width>
					<height>64</height>
					<aligny>center</aligny>
					<font>kscape_info_head</font>
					<textcolor>FFFFFFFF</textcolor>
					<label>$INFO[Window.Property(title)]</label>
					<visible>String.IsEmpty(Window.Property(clearlogo))</visible>
				</control>
				<control type="image">
					<description>Clear logo in place of the title</description>
					<left>30</left>
					<top>5</top>
					<width>620</width>
					<height>54</height>
					<aspectratio align="left" aligny="center">keep</aspectratio>
					<fadetime>150</fadetime>
					<texture background="true">$INFO[Window.Property(clearlogo)]</texture>
					<visible>!String.IsEmpty(Window.Property(clearlogo))</visible>
				</control>''')
    return out
