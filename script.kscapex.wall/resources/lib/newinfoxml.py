"""KScapeX "New wall test": the movie info screen in its cinema look.

script-kscape-info-new.xml is the classic fiche (script-kscape-info.xml, hand-written)
transformed by transform() below - tools/gen_wall_xml.py writes it at build time, and the
classic file is never touched. The fiche keeps every control id, position and page, so
details.py drives both without knowing which one is open; only the dressing changes:

It is flat, like the wall it belongs to: no gradient, no shadow, no gloss, no zoom.

- the panel is solid dark (kscape_bg) instead of opaque blue, the left column a shade
  darker, the header strip a quiet band; nothing is drawn behind the fiche, so the wall
  shows around it as it does for the classic one;
- the clear logo (Window.Property(clearlogo)) replaces the title when the library has one;
- it opens and closes as a plain fade instead of sliding up from the bottom - the wall
  behind already shows the same fanart, so the small panel reads as dissolving into the
  full fiche.

The wall opens this fiche only from New wall test (WallWindow.info_xml); everything else
keeps the classic one.
"""

NAME = 'script-kscape-info-new.xml'
REDUCED = '!String.IsEqual(Window(Home).Property(kscape.reduced),1)'

def _swap(xml, old, new, count=1):
    found = xml.count(old)
    if found != count:
        raise ValueError(f'newinfoxml: expected {count} of {old[:60]!r}, found {found} - '
                         f'script-kscape-info.xml has changed; update newinfoxml.py')
    return xml.replace(old, new)


def transform(xml):
    """script-kscape-info-new.xml from the classic fiche's XML."""
    out = _swap(xml, '''<!-- Movie info screen (resources/lib/details.py). Hand-written.''',
                '''<!-- GENERATED by tools/gen_wall_xml.py from script-kscape-info.xml (resources/lib/newinfoxml.py):
     the cinema fiche of New wall test. Do not edit by hand; edit the classic file or the transform.
     Movie info screen (resources/lib/details.py).''')
    # It opens and closes as a plain fade (no slide from the bottom, nothing growing).
    out = _swap(out, f'''				<animation effect="slide" start="0,1032" end="0,0" time="420" tween="cubic" easing="out" condition="{REDUCED}">WindowOpen</animation>
				<animation effect="fade" start="0" end="100" time="160" condition="{REDUCED}">WindowOpen</animation>
				<animation effect="slide" start="0,0" end="0,1032" time="300" tween="cubic" easing="in" condition="{REDUCED}">WindowClose</animation>''',
                f'''				<animation effect="fade" start="0" end="100" time="260" condition="{REDUCED}">WindowOpen</animation>
				<animation effect="fade" start="100" end="0" time="200" condition="{REDUCED}">WindowClose</animation>''')
    # Smoked glass instead of opaque blue.
    out = _swap(out, '''				<control type="image">
					<width>1728</width>
					<height>984</height>
					<texture colordiffuse="kscape_blue">kscape-white.png</texture>
				</control>''', '''				<control type="image">
					<description>Solid panel, no gradient and no transparency</description>
					<width>1728</width>
					<height>984</height>
					<texture colordiffuse="kscape_bg">kscape-white.png</texture>
				</control>''')
    out = _swap(out, '''					<description>Left column</description>
					<top>64</top>
					<width>480</width>
					<height>920</height>
					<texture colordiffuse="kscape_blue_dark">kscape-white.png</texture>''',
                '''					<description>Left column</description>
					<top>64</top>
					<width>480</width>
					<height>920</height>
					<texture colordiffuse="59000000">kscape-white.png</texture>''')
    # Header: a quiet band with a line in the theme colour, the clear logo in place of the title.
    out = _swap(out, '''				<control type="image">
					<description>Header strip</description>
					<width>1728</width>
					<height>64</height>
					<texture colordiffuse="kscape_blue_head">kscape-white.png</texture>
				</control>''', '''				<control type="image">
					<description>Header strip (quiet)</description>
					<width>1728</width>
					<height>64</height>
					<texture colordiffuse="46000000">kscape-white.png</texture>
				</control>''')
    out = _swap(out, '''				<control type="label">
					<left>30</left>
					<width>1660</width>
					<height>64</height>
					<aligny>center</aligny>
					<font>kscape_info_head</font>
					<textcolor>FFFFFFFF</textcolor>
					<label>$INFO[Window.Property(title)]</label>
				</control>''', '''				<control type="label">
					<left>30</left>
					<width>1660</width>
					<height>64</height>
					<aligny>center</aligny>
					<font>kscape_info_head</font>
					<textcolor>FFFFFFFF</textcolor>
					<label>$INFO[Window.Property(title)]</label>
					<visible>String.IsEmpty(Window.Property(clearlogo))</visible>
				</control>
				<control type="image">
					<description>Clear logo in place of the title</description>
					<left>30</left>
					<top>5</top>
					<width>620</width>
					<height>54</height>
					<aspectratio align="left" aligny="center">keep</aspectratio>
					<fadetime>150</fadetime>
					<texture background="true">$INFO[Window.Property(clearlogo)]</texture>
					<visible>!String.IsEmpty(Window.Property(clearlogo))</visible>
				</control>''')
    return out
